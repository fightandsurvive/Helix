-- Migration 06 — Per-move loss storage and weakness insight cache.
--
-- Per-move losses are stored ONLY for personal games (app.personal_games).
-- The GM warehouse (13.2M games) does not need per-move detail — its
-- analytics live at the aggregate level (gm.position_stats). This keeps
-- storage bounded: ~200 bytes/move × 40 moves × N_games. A user with
-- 10,000 games produces ~80 MB — trivial.
--
-- Weakness insights are a cache. The detector runs on-demand (or nightly)
-- and overwrites. Insights are the "derived" layer; per-move losses are
-- the "primitive" layer. Reruns of the detector are idempotent.
-- ══════════════════════════════════════════════════════════════════════

CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE analytics.move_losses (
    game_id       BIGINT NOT NULL REFERENCES app.personal_games(game_id) ON DELETE CASCADE,
    ply_number    SMALLINT NOT NULL,
    move_san      TEXT NOT NULL,
    fen_before    TEXT NOT NULL,
    eval_before_cp INTEGER NOT NULL,
    eval_after_cp  INTEGER NOT NULL,
    loss_cp       SMALLINT NOT NULL CHECK (loss_cp >= 0),
    phase         TEXT NOT NULL CHECK (phase IN ('Opening','Middlegame','Endgame')),
    piece_moved   CHAR(1) NOT NULL CHECK (piece_moved IN ('P','N','B','R','Q','K')),
    to_square     CHAR(2) NOT NULL,
    board_region  TEXT NOT NULL CHECK (board_region IN ('kingside','queenside','center')),
    clock_seconds INTEGER,
    PRIMARY KEY (game_id, ply_number)
);

-- User's moves only (filtered at write time by user_color), so this
-- covers every move the user made — no color filter needed downstream.
CREATE INDEX ON analytics.move_losses (game_id);
CREATE INDEX ON analytics.move_losses ((game_id, phase));

-- Blunder-focused index — the most common query.
CREATE INDEX ON analytics.move_losses ((game_id, loss_cp))
    WHERE loss_cp >= 100;

-- Full eval curve per game (both colors, every ply) — powers the eval graph.
CREATE TABLE analytics.game_eval_curve (
    game_id       BIGINT NOT NULL REFERENCES app.personal_games(game_id) ON DELETE CASCADE,
    ply_number    SMALLINT NOT NULL,
    move_san      TEXT NOT NULL,
    fen_after     TEXT NOT NULL,
    white_eval_cp INTEGER NOT NULL,       -- from white's perspective
    played_by_user BOOLEAN NOT NULL,
    user_loss_cp  SMALLINT,                -- NULL for opponent plies
    PRIMARY KEY (game_id, ply_number)
);
CREATE INDEX ON analytics.game_eval_curve (game_id, ply_number);

-- Weakness insight cache. Regenerated by analytics/weakness.py.
CREATE TABLE analytics.weakness_insights (
    insight_id     BIGSERIAL PRIMARY KEY,
    profile_id     BIGINT NOT NULL REFERENCES app.player_profiles(profile_id) ON DELETE CASCADE,
    category       TEXT NOT NULL,                       -- 'phase', 'opening_white', 'piece', etc.
    severity       TEXT NOT NULL CHECK (severity IN ('critical','high','medium','low')),
    title          TEXT NOT NULL,
    description    TEXT NOT NULL,
    metric_name    TEXT NOT NULL,
    metric_value   REAL NOT NULL,
    baseline_value REAL,
    sample_size    INTEGER NOT NULL,
    confidence     REAL NOT NULL CHECK (confidence BETWEEN 0 AND 1),
    impact_score   REAL NOT NULL CHECK (impact_score BETWEEN 0 AND 1),
    action_type    TEXT NOT NULL,                       -- 'practice_phase', 'train_opening', ...
    action_label   TEXT NOT NULL,
    action_payload JSONB,
    evidence       JSONB,
    computed_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (profile_id, category, title)
);

CREATE INDEX ON analytics.weakness_insights (profile_id, impact_score DESC);
CREATE INDEX ON analytics.weakness_insights (profile_id, computed_at DESC);
